  final String language;
  const ServiceStrings(this.language);
  String t(String key) {
    final pair = labels[key];
    return pair == null
        ? key.replaceAll('_', ' ')
        : pair[language == 'kk' ? 1 : 0];
  }

  String title(ApiOperation op) {
    final path = op.path;
    if (path == '/v1/me/subscriptions/problems') return t('subscriptions');
    if (path.startsWith('/v1/me/subscriptions/problems/') &&
        op.method != 'GET') {
      return t(op.method == 'PUT' ? 'subscribe' : 'unsubscribe');
    }
    if (path.endsWith('/join')) {
      return t(op.method == 'POST' ? 'join' : 'unjoin');
    }
    if (path.endsWith('/actions')) return t('process');
    if (path.endsWith('/history')) return t('history');
    if (path.contains('/publication-confirmations')) {
      return t('publicationConsent');
    }
    if (path.endsWith('/membership-requests')) {
      return t(op.method == 'GET' ? 'membershipQueue' : 'requestMembership');
    }
    if (path.endsWith('/decisions')) return t('decideMembership');
    if (path.endsWith('/invitations')) {
      return t(op.method == 'POST' ? 'inviteResident' : 'invitations');
    }
    if (path.endsWith('/accept')) return t('accept');
    if (path.endsWith('/decline')) return t('decline');
    if (path.endsWith('/clarifications')) return t('clarify');
    if (path.endsWith('/withdraw')) return t('withdraw');
    if (path.endsWith('/unpublish')) return t('unpublish');
    if (path.endsWith('/preview')) return t('preview');
    if (path.endsWith('/publish')) return t('publish');
    if (path.endsWith('/cancel')) return t('cancelAlert');
    if (path.endsWith('/read')) return t('read');
    if (path.endsWith('/read-all')) return t('readAll');
    if (path.endsWith('/unread-count')) return t('unread_count');
    if (path.endsWith('/user-restrictions')) return t('userRestrictions');
    if (path.endsWith('/approve')) return t('approvePhoto');
    if (path.endsWith('/redact')) return t('redactPhoto');
    if (op.method == 'PATCH') return t('edit');
    if (op.method == 'DELETE') {
      return t(path.contains('house-memberships') ? 'leaveHouse' : 'remove');
    }
    if (op.method == 'PUT') return t('save');
    if (op.method == 'POST') return t('create');
    final parts = path.split('/');
    return t(parts.last.startsWith('{') ? parts[parts.length - 2] : parts.last);
  }

